#!/usr/bin/env python3
"""Bakes vector symbols into anti-aliased alpha masks: src/ui/glyphs.cpp.

The firmware's own shapes are drawn from primitives (ui/icons.cpp); symbols with real curves (the
phone handsets of a call) come from Material Symbols paths (Apache License 2.0, Google), rasterised
here once at 16× supersampling and scaled on the glass from the mask.

    python3 scripts/build_glyphs.py
"""
import re
from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 96  # mask side in pixels
SS = 16    # supersampling

# 24 × 24 viewBox paths, Material Icons "call" and "call_end" (Apache 2.0).
GLYPHS = {
    "call": "M20.01 15.38c-1.23 0-2.42-.2-3.53-.56-.35-.12-.74-.03-1.01.24l-1.57 1.97c-2.83-1.35-5.48-3.9-6.89-6.83"
            "l1.95-1.66c.27-.28.35-.67.24-1.02-.37-1.11-.56-2.3-.56-3.53 0-.54-.45-.99-.99-.99H4.19C3.65 3 3 3.24 3 "
            "3.99 3 13.28 10.73 21 20.01 21c.71 0 .99-.63.99-1.18v-3.45c0-.54-.45-.99-.99-.99z",
    "call_end": "M12 9c-1.6 0-3.15.25-4.6.72v3.1c0 .39-.23.74-.56.9-.98.49-1.87 1.12-2.66 1.85-.18.18-.43.28-.7.28"
                "-.28 0-.53-.11-.71-.29L.29 13.08c-.18-.17-.29-.42-.29-.7 0-.28.11-.53.29-.71C3.34 8.78 7.46 7 12 7"
                "s8.66 1.78 11.71 4.67c.18.18.29.43.29.71 0 .28-.11.53-.29.71l-2.48 2.48c-.18.18-.43.29-.71.29-.27 "
                "0-.52-.11-.7-.28-.79-.74-1.69-1.36-2.67-1.85-.33-.16-.56-.5-.56-.9v-3.1C15.15 9.25 13.6 9 12 9z",
}


def tokens(d):
    for m in re.finditer(r"[MmLlHhVvCcSsZz]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?", d):
        yield m.group(0)


def flatten(d, steps=24):
    """The path's contours as point lists (cubic Béziers flattened)."""
    contours, pts = [], []
    x = y = 0.0
    last_ctrl = None
    cmd = None
    toks = list(tokens(d))
    i = 0

    def num():
        nonlocal i
        v = float(toks[i])
        i += 1
        return v

    def cubic(p0, p1, p2, p3):
        for k in range(1, steps + 1):
            t = k / steps
            mt = 1 - t
            pts.append((mt**3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t**3 * p3[0],
                        mt**3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t**3 * p3[1]))

    while i < len(toks):
        if re.fullmatch(r"[A-Za-z]", toks[i]):
            cmd = toks[i]
            i += 1
            if cmd in "Zz":
                if pts:
                    contours.append(pts)
                pts = []
                last_ctrl = None
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            if pts:
                contours.append(pts)
            pts = [(x, y)]
            cmd = "l" if rel else "L"
            last_ctrl = None
        elif c == "L":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            pts.append((x, y))
            last_ctrl = None
        elif c == "H":
            nx = num()
            x = x + nx if rel else nx
            pts.append((x, y))
            last_ctrl = None
        elif c == "V":
            ny = num()
            y = y + ny if rel else ny
            pts.append((x, y))
            last_ctrl = None
        elif c in "CS":
            if c == "C":
                x1, y1 = num(), num()
                if rel:
                    x1, y1 = x + x1, y + y1
            else:
                x1, y1 = (2 * x - last_ctrl[0], 2 * y - last_ctrl[1]) if last_ctrl else (x, y)
            x2, y2, ex, ey = num(), num(), num(), num()
            if rel:
                x2, y2, ex, ey = x + x2, y + y2, x + ex, y + ey
            cubic((x, y), (x1, y1), (x2, y2), (ex, ey))
            last_ctrl = (x2, y2)
            x, y = ex, ey
    if pts:
        contours.append(pts)
    return contours


def bake(d):
    big = SIZE * SS
    img = Image.new("L", (big, big), 0)
    draw = ImageDraw.Draw(img)
    # 24-unit viewBox with a unit of margin, into the mask.
    k = big / 24.0
    for contour in flatten(d):
        draw.polygon([(px * k, py * k) for px, py in contour], fill=255)
    return img.resize((SIZE, SIZE), Image.BOX)


def main():
    root = Path(__file__).resolve().parent.parent
    out = ["// Generated by scripts/build_glyphs.py - do not edit.",
           "// Material Icons \"call\", \"call_end\": Apache License 2.0, Copyright Google LLC.",
           "",
           '#include "ui/glyphs.h"',
           "",
           "namespace monav::ui::glyphs {",
           ""]
    for name, d in GLYPHS.items():
        data = bake(d).tobytes()
        ident = "k" + "".join(p.capitalize() for p in name.split("_"))
        out.append(f"const uint8_t {ident}[{SIZE} * {SIZE}] = {{")
        for r in range(SIZE):
            row = data[r * SIZE:(r + 1) * SIZE]
            out.append("    " + ",".join(str(b) for b in row) + ",")
        out.append("};")
        out.append("")
    out.append("}  // namespace monav::ui::glyphs")
    (root / "src/ui/glyphs.cpp").write_text("\n".join(out) + "\n")
    print("wrote src/ui/glyphs.cpp")


if __name__ == "__main__":
    main()
